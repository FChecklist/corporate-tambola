// Verifies the developer documentation in docs/dev against the real repository. Run from anywhere:  node tools/check-dev-docs.mjs
//   (a) every backticked repo path in docs/dev/*.md exists (a trailing :line or :line-line must lie inside the file);
//       a bare file name such as `worker.ts` must match at least one real file
//   (b) every route string found in the route-matching code of apps/edge/src/*.ts appears in 04-API-REFERENCE.md
//   (c) every table created in apps/edge/src/*.ts (SCHEMA parts) and in apps/edge/migrations/*.sql appears in 03-DATABASE.md,
//       and the two definitions name the same tables
//   (d) every file from `git ls-files -co --exclude-standard` (minus EXCLUDE below) appears in 02-FILE-MAP.md
// Exit code 0 = all good, 1 = at least one gap (each is printed). Read-only: it never writes anything.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const DEV = join(ROOT, "docs", "dev");
const read = (p) => readFileSync(join(ROOT, p), "utf8");
const problems = [];
const fail = (area, msg) => problems.push(`[${area}] ${msg}`);

// ---------------------------------------------------------------- the file list (d) and the exclusions
// Patterns that are NOT expected in 02-FILE-MAP.md. Each is explained in that document's introduction.
const EXCLUDE = [
  /^node_modules\//,          // installed packages
  /^docs\/dev\//,             // this documentation itself (listed in INDEX.md)
  /^test-results\//,          // Playwright output at the repo root
  /^pages\/public\//,         // generated by pages/build.mjs (git-ignored)
  /^data[^/]*\//,             // local data dumps: data/, data-pay/, data-pay2/, data-sim/, data-tmp/ (git-ignored)
  /\.sqlite/,                 // local SQLite databases (git-ignored)
  /^config\/(company\.json|live-secrets\.txt|platform-key\.txt|telemetry-report-key\.txt)$/, // secrets and local config (git-ignored)
  /^\.wrangler\//,
];
const git = (...a) => execFileSync("git", a, { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }).split("\n").map((s) => s.trim()).filter(Boolean);
const allFiles = git("ls-files", "-co", "--exclude-standard").filter((f) => existsSync(join(ROOT, f)));
const mapped = allFiles.filter((f) => !EXCLUDE.some((re) => re.test(f)));
const docs = readdirSync(DEV).filter((f) => f.endsWith(".md")).sort();
if (!docs.length) { console.error("docs/dev has no .md files"); process.exit(1); }
const text = Object.fromEntries(docs.map((f) => [f, readFileSync(join(DEV, f), "utf8")]));

// ---------------------------------------------------------------- (a) backticked paths
const TOP = ["apps/", "packages/", "pages/", "tools/", "tests/", "docs/", "config/", "design/", "reference/"];
const ROOTFILES = new Set(["package.json", "tsconfig.json", "README.md", "bun.lock", ".gitignore"]);
const EXT = /\.(ts|tsx|js|mjs|html|css|sql|md|py|toml|json|txt|webmanifest|mp4|xml|lock|png|webp|woff2)$/;
// names that legitimately do not exist in the repository (generated, git-ignored, external, or examples)
const NOT_IN_REPO = new Set([
  "_routes.json", "tambola.db", "company.json", "live-secrets.txt", "platform-key.txt", "telemetry-report-key.txt", "backup.sql", "bun.exe", "x.js",
  "tambola-local.sqlite", ".organizer-key", "server.log", "seed.json", "summary.json", "playwright-report.json", "wrangler.toml.bak", "0014_roles.sql.bak",
]);
const NOT_IN_REPO_PREFIX = [/^pages\/public\//, /^data[^/]*\//, /^config\/(company\.json|live-secrets|platform-key|telemetry-report-key)/, /^C:/, /^docs\/dev\//];
const fileSet = new Set(allFiles);
const byBase = new Map();
for (const f of allFiles) { const b = basename(f); if (!byBase.has(b)) byBase.set(b, []); byBase.get(b).push(f); }
const lineCount = new Map();
const lines = (f) => { if (!lineCount.has(f)) lineCount.set(f, readFileSync(join(ROOT, f), "utf8").split("\n").length); return lineCount.get(f); };
let pathRefs = 0;
for (const [doc, md] of Object.entries(text)) {
  const noFences = md.replace(/```[\s\S]*?```/g, (m) => m.split("\n").map(() => "").join("\n")); // code blocks are examples, not references
  for (const m of noFences.matchAll(/`([^`\n]+)`/g)) {
    let t = m[1].trim();
    if (!t || /[\s<>{}$*|=;,()\u2026]/.test(t) || t.includes("...") || t.startsWith("/") || /^https?:/i.test(t) || t.startsWith("@") || t.startsWith("-") || t.startsWith("\\")) continue;
    let lineSpec = null;
    const lm = t.match(/^(.*?):(\d+)(?:-(\d+))?(?:,\d+(?:-\d+)?)*$/);
    if (lm) { t = lm[1]; lineSpec = [Number(lm[2]), Number(lm[3] ?? lm[2])]; }
    t = t.replace(/#.*$/, "").replace(/^\.\//, "");
    if (!t) continue;
    const isTop = TOP.some((p) => t.startsWith(p)) || ROOTFILES.has(t);
    const isBareFile = !t.includes("/") && EXT.test(t) && /^[A-Za-z0-9_.\[\]-]+$/.test(t);
    if (!isTop && !isBareFile) continue;
    if (NOT_IN_REPO.has(basename(t)) || NOT_IN_REPO_PREFIX.some((re) => re.test(t))) continue;
    pathRefs++;
    if (isBareFile) {
      const hits = byBase.get(t);
      if (!hits) fail("a", `${doc}: bare file name \`${t}\` matches no file in the repository`);
      else if (lineSpec && hits.length === 1 && lineSpec[1] > lines(hits[0]) + 2) fail("a", `${doc}: \`${t}:${lineSpec[0]}\` is past the end of ${hits[0]} (${lines(hits[0])} lines)`);
      continue;
    }
    const isDir = t.endsWith("/");
    const p = isDir ? t.slice(0, -1) : t;
    if (!existsSync(join(ROOT, p))) { fail("a", `${doc}: path \`${t}\` does not exist`); continue; }
    if (!isDir && lineSpec && statSync(join(ROOT, p)).isFile() && lineSpec[1] > lines(p) + 2) fail("a", `${doc}: \`${t}:${lineSpec[0]}${lineSpec[1] !== lineSpec[0] ? "-" + lineSpec[1] : ""}\` is past the end of the file (${lines(p)} lines)`);
  }
}

// ---------------------------------------------------------------- (b) routes
const api = text["04-API-REFERENCE.md"] ?? "";
const ROUTE_FILES = ["worker.ts", "pay.ts", "partners.ts", "helpdesk.ts", "mode.ts", "visits.ts", "lifecycle.ts", "audit.ts"].map((f) => `apps/edge/src/${f}`);
const routeStrings = new Set(), routeWords = new Set();
for (const f of ROUTE_FILES) {
  const src = read(f);
  for (const m of src.matchAll(/"(\/(?:api|ai)\/[A-Za-z0-9_\-\/.]*)"/g)) routeStrings.add(m[1].replace(/\/$/, ""));
  // regex literals that match routes, e.g. /^\/api\/owner\/visits\/(summary|journey\/(...))$/ : take every plain-word alternative of every group and every plain literal segment
  for (const m of src.matchAll(/\/\^\\\/(?:api|ai)\\\/[^\n]*?\$\//g)) {
    const lit = m[0];
    for (const g of lit.matchAll(/\(([^()]*)\)/g)) for (const alt of g[1].split("|")) { const w = alt.replace(/\\\//g, "/").replace(/^\//, ""); if (/^[a-z][a-z-]{2,30}(\/[a-z-]+)?$/.test(w)) routeWords.add("/" + w); }
    for (const seg of lit.matchAll(/\\\/([a-z][a-z-]{2,30})(?=\\\/|\$|\(|\)|\/)/g)) routeWords.add("/" + seg[1]);
  }
}
for (const w of ["/vote", "/status", "/start", "/map", "/facts", "/go"]) routeWords.add(w);
for (const r of routeStrings) { if (r === "/api" || r === "/ai") continue; if (!api.includes(r)) fail("b", `route string "${r}" (apps/edge/src) is missing from 04-API-REFERENCE.md`); }
for (const w of routeWords) { if (!api.includes(w)) fail("b", `route segment "${w}" (regex in apps/edge/src) is missing from 04-API-REFERENCE.md`); }
// the engagement action list in the router regex must each appear as /api/z/{id}/<action>
const router = read("apps/edge/src/worker.ts").match(/\\\/api\\\/z\\\/\(\[A-Za-z0-9_-\]\{4,40\}\)\\\/\(([a-z|-]+)\)\$/);
if (!router) fail("b", "could not find the engagement action regex in worker.ts (checker needs updating)");
else for (const a of router[1].split("|")) if (!new RegExp("/api/z/\\{id\\}/" + a + "\\b").test(api)) fail("b", `engagement action "${a}" is not documented as /api/z/{id}/${a}`);
// the Pages functions
for (const r of ["/api/telemetry"]) if (!api.includes(r)) fail("b", `${r} missing`);

// ---------------------------------------------------------------- (c) tables
const dbdoc = text["03-DATABASE.md"] ?? "";
const tablesIn = (src) => [...src.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((m) => m[1]);
const codeTables = new Set(), migTables = new Set();
for (const f of readdirSync(join(ROOT, "apps/edge/src")).filter((f) => f.endsWith(".ts"))) for (const t of tablesIn(read("apps/edge/src/" + f))) codeTables.add(t);
for (const f of readdirSync(join(ROOT, "apps/edge/migrations")).filter((f) => f.endsWith(".sql")).sort()) {
  for (const t of tablesIn(read("apps/edge/migrations/" + f))) migTables.add(t);
  if (!dbdoc.includes(f)) fail("c", `migration file ${f} is not mentioned in 03-DATABASE.md`);
}
for (const t of codeTables) if (!new RegExp("(`|\\*\\*)" + t + "(`|\\*\\*)").test(dbdoc)) fail("c", `table ${t} (SCHEMA in apps/edge/src) is missing from 03-DATABASE.md`);
for (const t of migTables) if (!codeTables.has(t)) fail("c", `table ${t} exists in migrations/*.sql but not in SCHEMA (apps/edge/src)`);
for (const t of codeTables) if (!migTables.has(t)) fail("c", `table ${t} exists in SCHEMA but in no migration file`);
const tel = read("pages/functions/api/telemetry.ts").match(/CREATE TABLE IF NOT EXISTS (\w+)/);
if (tel && !dbdoc.includes("`" + tel[1] + "`") && !dbdoc.includes("**" + tel[1] + "**")) fail("c", `table ${tel[1]} (pages/functions/api/telemetry.ts) is missing from 03-DATABASE.md`);

// ---------------------------------------------------------------- (d) file map
const fm = text["02-FILE-MAP.md"] ?? "";
for (const f of mapped) if (!fm.includes("`" + f + "`")) fail("d", `file ${f} is not in 02-FILE-MAP.md`);

// ---------------------------------------------------------------- (e) the index lists every document
const idx = text["INDEX.md"] ?? "";
for (const d of docs) if (d !== "INDEX.md" && !idx.includes(d)) fail("e", `INDEX.md does not list ${d}`);

// ---------------------------------------------------------------- report
console.log(`docs checked: ${docs.length}; path references checked: ${pathRefs}; route strings: ${routeStrings.size}; route words: ${routeWords.size}; tables: ${codeTables.size}; mapped files: ${mapped.length} (of ${allFiles.length}, ${allFiles.length - mapped.length} excluded)`);
if (problems.length) { console.log(`\n${problems.length} problem(s):`); for (const p of problems) console.log("  - " + p); process.exit(1); }
console.log("OK: docs/dev matches the repository (paths, routes, tables, file map, index).");
